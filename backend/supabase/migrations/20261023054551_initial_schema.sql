-- Application tables live outside Supabase's exposed public schema.
CREATE SCHEMA IF NOT EXISTS app_private;
REVOKE ALL ON SCHEMA app_private FROM PUBLIC, anon, authenticated;

CREATE TABLE app_private.user_roles (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL,
  role text NOT NULL DEFAULT 'pending'
    CHECK (role IN ('pending', 'coordinator', 'responder')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app_private.reports (
  id text PRIMARY KEY,
  description text NOT NULL,
  location text,
  received_at text NOT NULL,
  status text NOT NULL DEFAULT 'QUEUED',
  urgency text NOT NULL DEFAULT 'UNKNOWN',
  extraction_json text,
  processing_metadata_json text,
  ai_consent boolean NOT NULL DEFAULT false,
  reviewed boolean NOT NULL DEFAULT false
);
CREATE INDEX reports_received_idx ON app_private.reports(received_at DESC);

CREATE TABLE app_private.jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id text NOT NULL UNIQUE REFERENCES app_private.reports(id),
  status text NOT NULL DEFAULT 'QUEUED',
  attempts integer NOT NULL DEFAULT 0,
  available_at text NOT NULL,
  lease_until text,
  last_error text
);
CREATE INDEX jobs_claim_idx ON app_private.jobs(status, available_at);

CREATE TABLE app_private.idempotency_keys (
  key text PRIMARY KEY,
  report_id text NOT NULL REFERENCES app_private.reports(id)
);

CREATE TABLE app_private.incidents (
  id text PRIMARY KEY,
  title text NOT NULL,
  summary text NOT NULL,
  status text NOT NULL DEFAULT 'OPEN',
  location text,
  created_at text NOT NULL,
  version integer NOT NULL DEFAULT 1
);

CREATE TABLE app_private.associations (
  report_id text NOT NULL REFERENCES app_private.reports(id),
  incident_id text NOT NULL REFERENCES app_private.incidents(id),
  state text NOT NULL DEFAULT 'CONFIRMED' CHECK(state IN ('CONFIRMED', 'REJECTED')),
  created_at text NOT NULL,
  PRIMARY KEY(report_id, incident_id)
);

CREATE TABLE app_private.extraction_records (
  id text PRIMARY KEY,
  report_id text NOT NULL REFERENCES app_private.reports(id),
  version integer NOT NULL,
  provider text NOT NULL,
  model text,
  prompt_hash text,
  schema_version text NOT NULL,
  validation_state text NOT NULL,
  duration_ms integer NOT NULL,
  token_usage_json text,
  result_json text NOT NULL,
  created_at text NOT NULL,
  UNIQUE(report_id, version)
);

CREATE TABLE app_private.tasks (
  id text PRIMARY KEY,
  incident_id text NOT NULL REFERENCES app_private.incidents(id),
  title text NOT NULL,
  description text NOT NULL,
  status text NOT NULL DEFAULT 'PROPOSED',
  assignee text,
  created_at text NOT NULL,
  version integer NOT NULL DEFAULT 1
);

CREATE TABLE app_private.audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor text NOT NULL,
  action text NOT NULL,
  target_type text NOT NULL,
  target_id text NOT NULL,
  created_at text NOT NULL,
  detail text
);

-- The public Data API cannot access this schema. RLS is enabled as defense in depth.
ALTER TABLE app_private.user_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.idempotency_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.incidents ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.associations ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.extraction_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.audit ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA app_private FROM PUBLIC, anon, authenticated;
